def build_npc_prompt(name):
    """把一个 NPC 的数据拼成 system prompt。"""
    npc = NPCS[name]
    lines = [npc["persona"], npc["goal"], ""]

    lines.append("【你知道的事实（绝不主动说出）】")
    lines += [f"- {k}" for k in npc["knowledge"]]

    lines.append("")
    lines.append("【你必须隐瞒的秘密（被直接问到时否认或转移话题）】")
    lines += [f"- {s}" for s in npc["secrets"]]

    lines.append("")
    lines.append("【你对外使用的说法】")
    lines += [f"- {c}" for c in npc["cover_story"]]

    lines.append("")
    lines.append(
        "【行为规则】\n"
        "- 你绝不主动承认任何秘密。\n"
        "- 当你收到『你被戳穿』的系统提示时，要表现出明显的动摇、慌乱、前后矛盾，"
        "但仍不直接认罪，可以逐渐松口。\n"
        "- 如果侦探只是凭空猜测、没有出示任何证据，你可以理直气壮地否认。\n"
        "- 回答要口语化、简短（1~3 句），像真人对话。\n"
        "- 不要跳出角色，也不要提到你在扮演角色。"
    )
    return "\n".join(lines)


def check_pressure(name, message, notebook_text=""):
    """确定性判断：玩家这句话里，有没有"有效"地出示关键证据。

    返回 (命中的压力点列表, 因证据不足被挡下的 id 列表)。

    证据分级：光提到关键词没用，笔记本里必须真的记着这条证据。
    """
    text = message.lower()
    book = notebook_text.lower()
    hits, gated = [], []

    for point in NPCS[name].get("pressure_points", []):
        if not any(kw.lower() in text for kw in point["keywords"]):
            continue
        requires = point.get("requires", [])
        if requires and not any(r.lower() in book for r in requires):
            gated.append(point["id"])
            continue
        hits.append(point)

    return hits, gated
